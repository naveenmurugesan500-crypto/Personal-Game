/**
 * Filter prompts strictly matching the active partner's gender, level, and environment
 */
export function getPromptsForCouple(params: {
  allPrompts: Prompt[];
  targetGender: 'male' | 'female';
  level: CoupleLevel;
  environment: PlayEnvironment;
  promptType?: 'truth' | 'dare' | 'all';
}): Prompt[] {
  const { allPrompts, targetGender, level, environment, promptType = 'all' } = params;

  return allPrompts.filter((p) => {
    // Check prompt type
    if (promptType !== 'all' && p.type !== promptType) {
      return false;
    }

    // Check gender: if prompt has specific target gender, it must match or be 'both'
    if (p.targetGender && p.targetGender !== 'both' && p.targetGender !== targetGender) {
      return false;
    }

    // Check level: if prompt has coupleLevel, it must match
    if (p.coupleLevel && p.coupleLevel !== level) {
      return false;
    }

    // Check environment: dares have specific environments ('video_call' or 'direct_play' or 'both')
    if (p.environment && p.environment !== 'both' && p.environment !== environment) {
      return false;
    }

    return true;
  });
}
